"""The parts of the agent-project template (Step 39) that come from the platform itself.

template_data write   # regenerate them
template_data check   # they are current (part of `just check`)

Generated, so a new project always starts from what this commit of the platform deploys:

* ``templates/agent-project/platform.yml``: hidden copier answers. ``platform_ref`` is the commit
  whose signed images the platform's overlays pin, so the project's SDK (a git dependency at that
  commit) is the code in those images. ``platform_constraints`` are the third-party versions in
  the platform's ``uv.lock``, so the project resolves what the platform tested (and its 14-day
  cooldown) instead of whatever is newest.
  ``platform_images`` are the images those overlays pin, the base of the project's own images.
* ``template/platform.yaml``: the platform config.
* ``template/deploy/overlays/<env>/``: the platform's overlays, with the base and shared
  components taken from the platform repository at ``platform_ref`` and every environment name
  (namespace, OpenBao role and mount, Keycloak client) made the project's own.
* ``template/deploy/components/head-specs``, ``overlays/<env>/released``, ``releases/`` and
  ``promotion.yaml``: what ``agentctl deploy-config`` writes for the template's first agent, so
  a new project passes ``agentctl deploy-config --check`` as made.
"""

from __future__ import annotations

import re
import sys
import tempfile
import tomllib
from pathlib import Path

import yaml
from agent_governance.release_repo import ReleaseRepo

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "templates" / "agent-project"
FILES = TEMPLATE / "template"
REPO = "https://github.com/deivamanikailasam/AgenticAICorePlatform"
ENVS = ("dev", "staging", "prod")
HEADER = "# Generated by `just template-data` from this platform commit. Do not edit.\n"
AGENT = "AGENT-NAME-PLACEHOLDER"


def platform_ref() -> str:
    text = (ROOT / "deploy" / "overlays" / "dev" / "kustomization.yaml").read_text()
    found = re.search(r"# images from commit ([0-9a-f]{40})", text)
    if not found:
        raise SystemExit("template-data: deploy/overlays/dev names no image commit")
    return found.group(1)


def images() -> dict[str, str]:
    """The platform images dev pins, by service: ``<name>@sha256:...``."""
    doc = yaml.safe_load((ROOT / "deploy" / "overlays" / "dev" / "kustomization.yaml").read_text())
    return {
        i["name"].removeprefix("agent-platform/"): f"{i['newName']}@{i['digest']}"
        for i in doc["images"]
    }


def constraints() -> list[str]:
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    return sorted(
        f"{p['name']}=={p['version']}"
        for p in lock["package"]
        if "registry" in (p.get("source") or {})
    )


def answers() -> str:
    data = {
        "platform_repo": {"type": "str", "default": REPO, "when": False},
        "platform_ref": {"type": "str", "default": platform_ref(), "when": False},
        "platform_images": {"type": "yaml", "default": images(), "when": False},
        "platform_constraints": {"type": "yaml", "default": constraints(), "when": False},
    }
    return HEADER + yaml.safe_dump(data, sort_keys=False, width=100)


def _remote(path: str) -> str:
    return f"{REPO}//{path}?ref={{{{ platform_ref }}}}"


def overlay(env: str, name: str) -> str:
    text = (ROOT / "deploy" / "overlays" / env / name).read_text()
    text = text.replace(f"agent-platform-{env}", f"{{{{ project_slug }}}}-{env}")
    text = text.replace("  - ../../base\n", f"  - {_remote('deploy/base')}\n")
    for component in ("temporal-dev", "cluster"):
        text = text.replace(
            f"  - ../../components/{component}\n",
            f"  - {_remote(f'deploy/components/{component}')}\n",
        )
    text = text.replace("`just promote`", "`agentctl promote`")
    return text.replace("just deploy-config", "agentctl deploy-config")


def deploy_config() -> dict[Path, str]:
    """What agentctl deploy-config writes for a project with one agent and no releases yet."""
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "agents" / AGENT).mkdir(parents=True)
        (root / "agents" / AGENT / "agent.yaml").write_text(f"name: {AGENT}\nversion: 0.1.0\n")
        repo = ReleaseRepo(
            root, promote_command="agentctl promote", config_command="agentctl deploy-config"
        )
        for env in ("staging", "prod"):
            repo.save(env, {"agents": {}})
        files = repo.rendered()
        for env in ("staging", "prod"):
            path = root / "deploy" / "releases" / f"{env}.yaml"
            files[path] = path.read_text()
        out = {}
        for path, text in files.items():
            rel = path.relative_to(root)
            if AGENT in text:
                out[FILES / f"{rel}.jinja"] = text.replace(AGENT, "{{ agent_name }}")
            else:
                out[FILES / rel] = text
        return out


def rendered() -> dict[Path, str]:
    files = {
        TEMPLATE / "platform.yml": answers(),
        FILES / "platform.yaml": (ROOT / "platform.yaml").read_text(),
        FILES / "deploy" / "promotion.yaml": (ROOT / "deploy" / "promotion.yaml").read_text(),
    }
    for env in ENVS:
        for name in ("kustomization.yaml", "env.properties", "namespace.yaml"):
            files[FILES / "deploy" / "overlays" / env / f"{name}.jinja"] = overlay(env, name)
    return files | deploy_config()


def main(argv: list[str]) -> int:
    files = rendered()
    if argv[:1] == ["write"]:
        for path, text in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"template-data: wrote {path.relative_to(ROOT)}")
        return 0
    stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    for path in stale:
        print(
            f"template-data: {path.relative_to(ROOT)} is stale: run just template-data",
            file=sys.stderr,
        )
    print(f"template-data: {len(files)} generated files, {'stale' if stale else 'up to date'}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
