"""Generated deployment config (Step 38).

deploy_config write   # the agent specs each environment mounts, from agents/ and deploy/releases
deploy_config check   # the generated files are current

* **dev** (``deploy/components/head-specs``): every spec in ``agents/`` at main's head, mounted
  at ``/app/agents`` in the pods that run agents.
* **staging, prod** (``deploy/overlays/<env>/released``): the snapshots the environment's
  releases file names (``deploy/specs/<agent>/<version>/``). agent-api mounts every named version
  at ``/app/versions/<agent>/<version>/`` with the releases file, so it can serve a canary or
  shadow candidate next to the stable version; agent-worker and a2a-gateway mount each agent's
  stable version at ``/app/agents/<agent>/``.

A ConfigMap key cannot contain "/", so each file is stored under its path with "/" written as
"--" and mounted back at its path (``items``).
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "agents"
HEAD = ROOT / "deploy" / "components" / "head-specs"
HEADER = "# Generated by `just deploy-config`. Do not edit.\n"
RELEASED_ENVS = ("staging", "prod")


def version_files(root: Path) -> list[str]:
    files = [*root.glob("agent.yaml"), *root.glob("workers/*.yaml")]
    return sorted(str(p.relative_to(root)) for p in files)


def key(path: str) -> str:
    return path.replace("/", "--")


def dump(doc: Any) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False)


def mount(name: str, configmap: str, items: list[tuple[str, str]], at: str) -> list[dict[str, Any]]:
    return [
        {
            "op": "add",
            "path": "/spec/template/spec/volumes/-",
            "value": {
                "name": name,
                "configMap": {
                    "name": configmap,
                    "items": [{"key": k, "path": p} for k, p in items],
                },
            },
        },
        {
            "op": "add",
            "path": "/spec/template/spec/containers/0/volumeMounts/-",
            "value": {"name": name, "mountPath": at, "readOnly": True},
        },
    ]


def head_specs() -> dict[Path, str]:
    paths = [
        f"{a.name}/{f}" for a in sorted(AGENTS.iterdir()) if a.is_dir() for f in version_files(a)
    ]
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1",
        "kind": "Component",
        "configMapGenerator": [
            {"name": "agent-specs", "files": [f"{key(p)}=../../../agents/{p}" for p in paths]}
        ],
        "patches": [
            {
                "path": "volume.yaml",
                "target": {"kind": "Deployment", "labelSelector": "agent-platform/specs=mounted"},
            }
        ],
    }
    volume = mount("agent-specs", "agent-specs", [(key(p), p) for p in paths], "/app/agents")
    return {HEAD / "kustomization.yaml": dump(kustomization), HEAD / "volume.yaml": dump(volume)}


def released(env: str) -> dict[Path, str]:
    out = ROOT / "deploy" / "overlays" / env / "released"
    data = yaml.safe_load((ROOT / "deploy" / "releases" / f"{env}.yaml").read_text()) or {}
    entries = data.get("agents") or {}
    files: list[str] = []  # <agent>/<version>/<file>
    stable: list[tuple[str, str]] = []  # (key, <agent>/<file>)
    for agent, entry in sorted(entries.items()):
        versions = [str(entry["stable"])]
        if entry.get("candidate"):
            versions.append(str(entry["candidate"]["version"]))
        for version in versions:
            root = ROOT / "deploy" / "specs" / agent / version
            for f in version_files(root):
                files.append(f"{agent}/{version}/{f}")
                if version == str(entry["stable"]):
                    stable.append((key(f"{agent}/{version}/{f}"), f"{agent}/{f}"))
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1alpha1",
        "kind": "Component",
        "configMapGenerator": [
            {"name": "agent-specs", "files": [f"{key(p)}=../../../specs/{p}" for p in files]},
            {"name": "agent-releases", "files": [f"releases.yaml=../../../releases/{env}.yaml"]},
        ],
        "patches": [
            {"path": "agent-api.yaml", "target": {"kind": "Deployment", "name": "agent-api"}},
            {
                "path": "stable.yaml",
                "target": {"kind": "Deployment", "name": "agent-worker|a2a-gateway"},
            },
        ],
    }
    api = [
        *mount("agent-specs", "agent-specs", [(key(p), p) for p in files], "/app/versions"),
        *mount(
            "agent-releases",
            "agent-releases",
            [("releases.yaml", "releases.yaml")],
            "/app/releases",
        ),
        {
            "op": "add",
            "path": "/spec/template/spec/containers/0/env/-",
            "value": {"name": "AGENT_API_RELEASES", "value": "/app/releases/releases.yaml"},
        },
        {
            "op": "add",
            "path": "/spec/template/spec/containers/0/env/-",
            "value": {"name": "AGENT_API_VERSIONS_DIR", "value": "/app/versions"},
        },
    ]
    return {
        out / "kustomization.yaml": dump(kustomization),
        out / "agent-api.yaml": dump(api),
        out / "stable.yaml": dump(mount("agent-specs", "agent-specs", stable, "/app/agents")),
    }


def rendered() -> dict[Path, str]:
    files = head_specs()
    for env in RELEASED_ENVS:
        files |= released(env)
    return files


def main(argv: list[str]) -> int:
    files = rendered()
    if argv[:1] == ["write"]:
        for path, text in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"deploy-config: wrote {path.relative_to(ROOT)}")
        return 0
    stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    for path in stale:
        print(
            f"deploy-config: {path.relative_to(ROOT)} is stale: run just deploy-config",
            file=sys.stderr,
        )
    print(f"deploy-config: {len(files)} generated files, {'stale' if stale else 'up to date'}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
