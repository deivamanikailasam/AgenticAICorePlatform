"""Generated deployment config (Step 38).

deploy_config write   # deploy/base/specs/: the agent-specs ConfigMap and the volume that mounts it
deploy_config check   # the generated files match agents/

A ConfigMap key cannot contain "/", so each spec file is stored under its path with "/" written
as "--" and mounted back at its path (``items``), giving pods the same ``agents/`` tree as the
repo: ``<agent>/agent.yaml`` and ``<agent>/workers/<name>.yaml``.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
AGENTS = ROOT / "agents"
OUT = ROOT / "deploy" / "base" / "specs"
HEADER = "# Generated by `just deploy-config` from agents/. Do not edit.\n"


def spec_paths() -> list[str]:
    files = [*AGENTS.glob("*/agent.yaml"), *AGENTS.glob("*/workers/*.yaml")]
    return sorted(str(p.relative_to(AGENTS)) for p in files)


def key(path: str) -> str:
    return path.replace("/", "--")


def rendered() -> dict[str, str]:
    paths = spec_paths()
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "configMapGenerator": [
            {
                "name": "agent-specs",
                "files": [f"{key(p)}=../../../agents/{p}" for p in paths],
            }
        ],
    }
    volume = [
        {
            "op": "add",
            "path": "/spec/template/spec/volumes/-",
            "value": {
                "name": "agent-specs",
                "configMap": {
                    "name": "agent-specs",
                    "items": [{"key": key(p), "path": p} for p in paths],
                },
            },
        },
        {
            "op": "add",
            "path": "/spec/template/spec/containers/0/volumeMounts/-",
            "value": {"name": "agent-specs", "mountPath": "/app/agents", "readOnly": True},
        },
    ]
    return {
        "kustomization.yaml": HEADER + yaml.safe_dump(kustomization, sort_keys=False),
        "volume.yaml": HEADER + yaml.safe_dump(volume, sort_keys=False),
    }


def main(argv: list[str]) -> int:
    files = rendered()
    if argv[:1] == ["write"]:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (OUT / name).write_text(text)
            print(f"deploy-config: wrote deploy/base/specs/{name}")
        return 0
    stale = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != t]
    for name in stale:
        print(
            f"deploy-config: deploy/base/specs/{name} is stale: run just deploy-config",
            file=sys.stderr,
        )
    print(f"deploy-config: {len(spec_paths())} spec files, {'stale' if stale else 'up to date'}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
