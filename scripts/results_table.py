"""The platform's results table (Step 40): only numbers that a run measured, each with its set
size and where it came from.

results_table write   # regenerate docs/results.md
results_table check   # it is current (part of `just check`)

Sources, and nothing else:

* ``evals/baselines/*.mechanics.json``: each app's mechanics baseline (stand-in gateway).
* ``evals/results/dr/*.json``: the disaster-recovery drill.
* ``evals/results/redteam/{unit,garak,promptfoo}.json``: recorded red-team runs.
* ``docs/results/ci-evidence.yaml``: numbers from CI runs, each with its workflow run ID.

Quality (task success on real models, judge scores, AUD and latency on real models) has no row
of numbers: no real-model run has been recorded. The page says so instead of estimating.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "results.md"
EVIDENCE = ROOT / "docs" / "results" / "ci-evidence.yaml"
REDTEAM = ("unit", "promptfoo", "garak")
REPO = "https://github.com/deivamanikailasam/AgenticAICorePlatform"


def _json(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text())
    return data


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def baselines() -> list[str]:
    rows = [
        "| App | Spec | Tasks | Succeeded | Tokens per task | Source |",
        "|---|---|---|---|---|---|",
    ]
    for path in sorted((ROOT / "evals" / "baselines").glob("*.mechanics.json")):
        d = _json(path)
        tasks = d["dataset"]["tasks"]
        usage = d.get("usage") or {}
        tokens = usage.get("tokens")
        per_task = f"{tokens / tasks:.1f}" if isinstance(tokens, int | float) and tasks else "-"
        rows.append(
            f"| {d['app']} | {d['versions']['spec']} | {tasks} | {d['succeeded']} of {tasks} "
            f"| {per_task} | `{_rel(path)}` |"
        )
    return rows


def redteam() -> list[str]:
    rows = [
        "| Run | Commit | Executed | Held | Findings | Categories with no executed attack | Source |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in REDTEAM:
        path = ROOT / "evals" / "results" / "redteam" / f"{name}.json"
        if not path.exists():
            continue
        d = _json(path)
        s = d["summary"]
        untested = ", ".join(s["untested"]) or "none"
        rows.append(
            f"| {', '.join(d['tiers'])} | {d['commit']} | {s['executed']} | {s['held']} "
            f"| {s['findings']} | {untested} | `{_rel(path)}` |"
        )
    return rows


def dr() -> list[str]:
    rows = [
        "| Drill | At | Writes acknowledged | Writes lost | RPO measured (target) "
        "| RTO measured (target) | Recovered and verified | Passed | Source |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for path in sorted((ROOT / "evals" / "results" / "dr").glob("*.json")):
        d = _json(path)
        m, t, v = d["measured"], d["targets"], d["verification"]
        recovered = (
            f"{v['runs_recovered']} runs, {v['checkpoints_recovered']} checkpoints, "
            f"{v['memories_recovered']} memories; audit chain "
            f"{'intact' if v['audit_chain_ok'] else 'broken'} ({v['audit_rows']} rows)"
        )
        rows.append(
            f"| {d['drill']} | {d['at']} | {d['writes_acknowledged']} | {d['writes_lost']} "
            f"| {m['rpo_seconds']} s ({t['rpo_seconds']} s) "
            f"| {m['rto_seconds']} s ({t['rto_seconds']} s) | {recovered} "
            f"| {'yes' if d['passed'] else 'no'} | `{_rel(path)}` |"
        )
    return rows


def ci() -> list[str]:
    rows = ["| Workflow run | Commit | Date | What | Result |", "|---|---|---|---|---|"]
    for run in yaml.safe_load(EVIDENCE.read_text())["runs"]:
        link = f"[{run['workflow']} {run['id']}]({REPO}/actions/runs/{run['id']})"
        for m in run["measured"]:
            detail = f" ({m['detail'].strip()})" if m.get("detail") else ""
            rows.append(
                f"| {link} | {run['commit']} | {run['date']} | {m['what']} | {m['value']}{detail} |"
            )
    return rows


def render() -> str:
    parts = [
        "# Results",
        "",
        "Generated by `just results` from recorded result files and CI runs. Do not edit.",
        "Every number below was measured by a run named in its row, with the size of the set it "
        "was measured on. Nothing here is an estimate.",
        "",
        "## What has not been measured",
        "",
        "- **Quality on real models.** No run with `--provider gateway` against real models has "
        "been recorded, so there is no task-success rate, judge score, AUD per task or latency "
        "for any app on a real model. These are VERIFY-ON-MAC: `just eval-app <app> --provider "
        "gateway` on the owner's machine records them.",
        "- **Judge agreement with people.** The judges' calibration needs human labels "
        "(`evals/labels/`), which haven't been given.",
        "- **Multi-agent against single-agent.** Whether the research-report team beats one agent "
        "on the same tasks needs the real-model runs above.",
        "",
        "## Mechanics baselines (stand-in gateway)",
        "",
        "The stand-in gateway answers with canned responses. These runs check that the harness "
        "and the platform work, and they are what CI gates regressions against. A low "
        "“succeeded” count here is expected for apps whose tasks need a real model's "
        "answer; it says nothing about quality.",
        "",
        *baselines(),
        "",
        "## CI runs",
        "",
        *ci(),
        "",
        "## Red-team runs recorded in the repository",
        "",
        "The red-team suite also runs in CI on every push (above). These are runs recorded as "
        "files; the attack libraries cover only the categories they have attacks for.",
        "",
        *redteam(),
        "",
        "## Disaster-recovery drill",
        "",
        *dr(),
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    text = render()
    if argv[:1] == ["write"]:
        OUT.write_text(text)
        print(f"results: wrote {_rel(OUT)}")
        return 0
    if not OUT.exists() or OUT.read_text() != text:
        print(f"results: {_rel(OUT)} is stale: run just results", file=sys.stderr)
        return 1
    print("results: up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
