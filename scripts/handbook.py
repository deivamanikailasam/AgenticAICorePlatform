"""The handbook's compiled pages (cross-cutting docs): gathered from the 40 step chapters and the
ADR index, so they say exactly what those say and can't fall behind them.

handbook write   # regenerate docs/handbook/{plain-english,when-to-choose,design-decisions}.md
handbook check   # they are current (part of `just check`)

* ``plain-english.md``: each step's goal, big idea and analogy, and its recap (sections 1, 2, 13).
* ``when-to-choose.md``: each step's alternatives and which approach fits (sections 9 and 10).
* ``design-decisions.md``: every ADR, grouped by the build's nine phases.

The other handbook pages (strategy, techniques, promotion, lifecycle) are written by hand.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUIDE = ROOT / "docs" / "guide"
ADRS = ROOT / "docs" / "adr" / "README.md"
OUT = ROOT / "docs" / "handbook"
HEADER = "<!-- Generated by `just handbook` from the step chapters and ADRs. Do not edit. -->\n"
PHASES = (
    ("A · Foundation", 1, 4),
    ("B · Models, tools and MCP", 5, 10),
    ("C · Runtime and patterns", 11, 17),
    ("D · State, memory and durability", 18, 21),
    ("E · Multi-agent and A2A", 22, 25),
    ("F · Safety, human in the loop and identity", 26, 29),
    ("G · Telemetry, audit and governance", 30, 32),
    ("H · Evals and red-teaming", 33, 36),
    ("I · Production and reuse", 37, 40),
)


def chapters() -> list[tuple[int, str, Path, dict[str, str]]]:
    out = []
    for path in sorted(GUIDE.glob("step-*.md")):
        text = path.read_text()
        title = text.splitlines()[0].removeprefix("# ").strip()
        number = int(re.match(r"step-(\d+)", path.name).group(1))  # type: ignore[union-attr]
        sections: dict[str, str] = {}
        for part in re.split(r"^## ", text, flags=re.M)[1:]:
            head, _, body = part.partition("\n")
            sections[head.split(".", 1)[0].strip()] = body.strip()
        out.append((number, title, path, sections))
    return out


def goal(glance: str) -> str:
    m = re.search(r"^\| \*\*Goal\*\* \| (.+?) \|$", glance, flags=re.M)
    return m.group(1).strip() if m else ""


def phase_of(step: int) -> str:
    return next(name for name, lo, hi in PHASES if lo <= step <= hi)


def plain_english() -> str:
    parts = [
        HEADER,
        "# The whole build in plain English",
        "",
        "Every step, in the words of its own chapter: what it was for, the idea behind it, and "
        "what it left behind. The full chapter is linked from each heading. Terms are in the "
        "[glossary](../glossary.md).",
        "",
    ]
    current = None
    for number, title, path, s in chapters():
        if phase_of(number) != current:
            current = phase_of(number)
            parts += [f"## Phase {current}", ""]
        parts += [
            f"### [{title}](../guide/{path.name})",
            "",
            f"**Goal:** {goal(s.get('1', ''))}",
            "",
            s.get("2", ""),
            "",
            f"**What it left behind:** {s.get('13', '')}",
            "",
        ]
    return "\n".join(parts)


def when_to_choose() -> str:
    parts = [
        HEADER,
        "# When to choose what",
        "",
        "For every step: the alternatives to what the platform chose, when each would win, and "
        "which approach fits which situation. Taken from section 9 and 10 of each chapter.",
        "",
    ]
    for _number, title, path, s in chapters():
        parts += [
            f"## [{title}](../guide/{path.name})",
            "",
            s.get("9", ""),
            "",
            "**Which fits which situation**",
            "",
            s.get("10", ""),
            "",
        ]
    return "\n".join(parts)


def design_decisions() -> str:
    rows = [line for line in ADRS.read_text().splitlines() if re.match(r"^\| \[\d{4}\]", line)]
    by_phase: dict[str, list[str]] = {name: [] for name, _, _ in PHASES}
    for row in rows:
        cells = [c.strip() for c in row.strip("|").split("|")]
        link = cells[0].replace("](", "](../adr/")
        step = int(re.match(r"\d+", cells[-1]).group(0))  # type: ignore[union-attr]
        by_phase[phase_of(step)].append(f"| {link} | {' | '.join(cells[1:-1])} | {step} |")
    parts = [
        HEADER,
        "# Design decisions",
        "",
        f"All {len(rows)} architecture decision records, by phase. Each ADR gives the context, the "
        "options considered and why they lost, and the consequences. The overview of how the "
        "pieces fit is in [the architecture](../architecture/README.md).",
        "",
    ]
    for name, _, _ in PHASES:
        parts += [f"## {name}", "", "| ADR | Decision | Step |", "|---|---|---|"]
        parts += by_phase[name] + [""]
    return "\n".join(parts)


def rendered() -> dict[Path, str]:
    return {
        OUT / "plain-english.md": plain_english(),
        OUT / "when-to-choose.md": when_to_choose(),
        OUT / "design-decisions.md": design_decisions(),
    }


def main(argv: list[str]) -> int:
    files = rendered()
    if argv[:1] == ["write"]:
        OUT.mkdir(parents=True, exist_ok=True)
        for path, text in files.items():
            path.write_text(text)
            print(f"handbook: wrote {path.relative_to(ROOT)}")
        return 0
    stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    for path in stale:
        print(f"handbook: {path.relative_to(ROOT)} is stale: run just handbook", file=sys.stderr)
    print(f"handbook: {len(files)} compiled pages, {'stale' if stale else 'up to date'}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
