"""Generate tool cards (and, from Step 32, agent and system cards) from the registries.

Source data goes to ``cards/<kind>/<name>.yaml`` (machine-readable, used for lineage and the AI
inventory); a rendered page goes to ``docs/cards/<kind>/<name>.md``. ``--check`` fails if either
is stale, so cards can never drift from the code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml
from agent_contracts.interfaces import Tool
from agent_contracts.models import SideEffect, ToolSpec
from agent_contracts.registry import registry

ROOT = Path(__file__).resolve().parent.parent

DEFAULT_RULE = {
    SideEffect.READ: "Allowed if the user may read the data.",
    SideEffect.WRITE: "Allowed with an idempotency key; logged.",
    SideEffect.IRREVERSIBLE: "Human approval required unless policy says otherwise; never retried automatically.",
}


def tool_specs() -> list[ToolSpec]:
    specs = []
    for reg in registry.registrations():
        if reg.slot != "tool" or reg.status == "dummy":
            continue
        cls = registry.get("tool", reg.name)
        tool = cls()
        assert isinstance(tool, Tool)
        specs.append(tool.spec)
    return sorted(specs, key=lambda s: s.name)


def card_data(spec: ToolSpec) -> dict[str, Any]:
    return {
        "kind": "tool",
        "name": spec.name,
        "version": spec.version,
        "ref": spec.ref,
        "owner": spec.owner,
        "purpose": spec.description,
        "side_effect": spec.side_effect.value,
        "default_rule": DEFAULT_RULE[spec.side_effect],
        "idempotent": spec.idempotent,
        "timeout_seconds": spec.timeout_seconds,
        "retry": spec.retry.model_dump(),
        "data_classification": spec.data_classification.value,
        "deprecated": spec.deprecated,
        "input_schema": spec.input_schema,
        "output_schema": spec.output_schema,
        "limitations": "Output is untrusted data and is never treated as instructions.",
        "eval_results": "none yet (agent evals start in Step 34)",
    }


def render(card: dict[str, Any]) -> str:
    rows = [
        ("Ref", f"`{card['ref']}`"),
        ("Version", card["version"]),
        ("Owner", card["owner"]),
        ("Side effect", f"`{card['side_effect']}` — {card['default_rule']}"),
        ("Idempotent", "yes" if card["idempotent"] else "no"),
        ("Timeout", f"{card['timeout_seconds']} s"),
        (
            "Retry",
            f"{card['retry']['max_attempts']} attempt(s), backoff {card['retry']['backoff_seconds']} s",
        ),
        ("Data classification", card["data_classification"]),
        ("Deprecated", "yes" if card["deprecated"] else "no"),
        ("Limitations", card["limitations"]),
        ("Eval results", card["eval_results"]),
    ]
    out = [
        f"# Tool card: `{card['name']}`",
        "",
        "Generated by `just cards` from the tool registry — do not edit by hand.",
        "",
        card["purpose"],
        "",
        "| Field | Value |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in rows],
        "",
        "## Input schema",
        "",
        "```json",
        json.dumps(card["input_schema"], indent=2),
        "```",
        "",
        "## Output schema",
        "",
        "```json",
        json.dumps(card["output_schema"], indent=2),
        "```",
        "",
    ]
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for spec in tool_specs():
        data = card_data(spec)
        files[ROOT / "cards" / "tools" / f"{spec.name}.yaml"] = yaml.safe_dump(
            data, sort_keys=False
        )
        files[ROOT / "docs" / "cards" / "tools" / f"{spec.name}.md"] = render(data)
    return files


def main(argv: list[str]) -> int:
    files = outputs()
    if argv and argv[0] == "--check":
        stale = [
            str(p.relative_to(ROOT))
            for p, text in files.items()
            if not p.exists() or p.read_text() != text
        ]
        known = {p for p in files}
        orphans = [
            str(p.relative_to(ROOT))
            for d in ("cards/tools", "docs/cards/tools")
            for p in (ROOT / d).glob("*")
            if p not in known
        ]
        print(
            f"cards: {'stale: ' + ', '.join(stale + orphans) if stale or orphans else 'up to date'}"
        )
        return 1 if stale or orphans else 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"cards: wrote {len(files)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
