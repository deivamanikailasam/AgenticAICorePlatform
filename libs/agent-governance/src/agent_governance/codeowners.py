"""Change approval by risk tier (Step 32): CODEOWNERS generated from the specs and
``governance/approvers.yaml``, and the merge gate's decision for a pull request.

CODEOWNERS asks GitHub for the right reviewers on every spec, by its risk tier. The gate is what
makes "a high-risk spec change cannot merge without the named approver" checkable in CI: a pull
request that changes a spec which is high-risk before or after the change, or the governance
files themselves, fails until a named ``high`` approver has approved its latest commit.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any

import yaml

from agent_governance.inventory import Inventory

ORDER = {"low": 0, "medium": 1, "high": 2}


def approvers_for(tier: str, approvers: Mapping[str, Any]) -> list[str]:
    return list((approvers.get("tiers") or {}).get(tier) or approvers.get("default") or [])


def render(inv: Inventory) -> str:
    a = inv.approvers
    lines = [
        "# Generated by `just cards` from governance/approvers.yaml and the agent specs — do not",
        "# edit by hand. Later lines win. Each spec is owned by the approvers of its risk tier.",
        "",
        f"* {' '.join(a.get('default') or [])}",
        "",
    ]
    for e in inv.entries:
        tier = e.spec.risk_tier.value
        lines.append(f"/{e.path} {' '.join(approvers_for(tier, a))}  # {tier}")
    apps = {e.system: e for e in inv.systems()}
    for name in sorted(apps):
        if (inv.root / "apps" / name).is_dir():
            tier = max(
                (m.spec.risk_tier.value for m in [apps[name], *inv.workers_of(name)]),
                key=ORDER.__getitem__,
            )
            lines.append(f"/apps/{name}/ {' '.join(approvers_for(tier, a))}  # {tier}")
    lines += ["", "# governance itself: the high-risk approvers"]
    high = " ".join(approvers_for("high", a))
    lines += [f"{p} {high}" for p in a.get("governance_paths") or []]
    lines.append("")
    return "\n".join(lines)


def risk_tier(text: str | None) -> str | None:
    """The ``risk_tier`` of a spec's YAML text (None if absent, unreadable or not a spec)."""
    if not text:
        return None
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError:
        return "high"  # unreadable: treat as the strictest case
    tier = doc.get("risk_tier") if isinstance(doc, dict) else None
    return str(tier) if tier else None


def is_spec(path: str) -> bool:
    parts = path.split("/")
    return parts[0] == "agents" and (
        (len(parts) == 3 and parts[2] == "agent.yaml")
        or (len(parts) == 4 and parts[2] == "workers" and parts[3].endswith((".yaml", ".yml")))
    )


@dataclass(frozen=True)
class Review:
    user: str
    state: str  # APPROVED, CHANGES_REQUESTED, COMMENTED, DISMISSED
    commit: str


@dataclass
class Decision:
    ok: bool
    needs: list[str] = field(default_factory=list)  # why the high approvers are needed
    approved_by: list[str] = field(default_factory=list)
    reason: str = ""


def decide(
    changed: Iterable[tuple[str, str | None, str | None]],
    reviews: Sequence[Review],
    head_sha: str,
    author: str,
    approvers: Mapping[str, Any],
) -> Decision:
    """``changed`` is (path, text at base, text at head) for each changed file."""
    gov = [p.strip("/") for p in approvers.get("governance_paths") or []]
    needs = []
    for path, before, after in changed:
        if is_spec(path):
            tiers = {risk_tier(before), risk_tier(after)}
            if "high" in tiers:
                needs.append(f"{path} is high-risk ({risk_tier(before)} -> {risk_tier(after)})")
        elif any(path == g or path.startswith(g + "/") for g in gov):
            needs.append(f"{path} is a governance file")
    if not needs:
        return Decision(True, reason="no high-risk spec or governance file changed")
    named = {u.lstrip("@").lower() for u in approvers_for("high", approvers) if "/" not in u}
    latest: dict[str, Review] = {}
    for r in reviews:  # in submission order: a later review replaces an earlier one
        latest[r.user.lower()] = r
    approved = sorted(
        u
        for u, r in latest.items()
        if r.state == "APPROVED" and r.commit == head_sha and u in named and u != author.lower()
    )
    if approved:
        return Decision(True, needs, approved, "approved by a named high-risk approver")
    return Decision(
        False,
        needs,
        [],
        "needs an approval of the latest commit from one of: "
        + ", ".join(f"@{u}" for u in sorted(named))
        + (" (the author can't approve their own change)" if author.lower() in named else ""),
    )
