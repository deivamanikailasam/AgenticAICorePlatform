"""A repository laid out for promotion (Step 38), used by the platform and by agent projects made
from the template (Step 39, ``agentctl promote``).

The layout, relative to the repository root::

    agents/<agent>/agent.yaml, workers/*.yaml     dev: what main's head runs
    deploy/specs/<agent>/<version>/               released snapshots (never change)
    deploy/releases/{staging,prod}.yaml           what each environment serves
    deploy/promotion.yaml                         the promotion policy (canary weight, modes)
    deploy/components/head-specs/                 generated: dev's specs as a ConfigMap
    deploy/overlays/<env>/released/               generated: the snapshots staging/prod mount

``ReleaseRepo`` reads the deployment state at a commit (for the promotion rules in
``agent_governance.promotion``), makes each promotion step as a change to these files, and renders
the generated deployment config. A ConfigMap key cannot contain "/", so each spec file is stored
under its path with "/" written as "--" and mounted back at its path (``items``).
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import urllib.request
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from agent_governance.promotion import ENVS, Policy, State, problems, tree_hash


class PromotionError(Exception):
    """A promotion step that can't be made (the message says why)."""


def version_files(root: Path) -> list[str]:
    files = [*root.glob("agent.yaml"), *root.glob("workers/*.yaml")]
    return sorted(str(p.relative_to(root)) for p in files)


def key(path: str) -> str:
    return path.replace("/", "--")


def mount(name: str, configmap: str, items: list[tuple[str, str]], at: str) -> list[dict[str, Any]]:
    return [
        {
            "op": "add",
            "path": "/spec/template/spec/volumes/-",
            "value": {
                "name": name,
                "configMap": {
                    "name": configmap,
                    "items": [{"key": k, "path": p} for k, p in items],
                },
            },
        },
        {
            "op": "add",
            "path": "/spec/template/spec/containers/0/volumeMounts/-",
            "value": {"name": name, "mountPath": at, "readOnly": True},
        },
    ]


@dataclass(frozen=True)
class Step:
    """One promotion step: the environment it changes, the version and what it does."""

    env: str
    version: str
    what: str

    def message(self, agent: str) -> str:
        return f"deploy({self.env}): {agent} {self.what}"


class ReleaseRepo:
    def __init__(
        self,
        root: Path,
        *,
        promote_command: str = "just promote",
        config_command: str = "just deploy-config",
    ) -> None:
        self.root = root
        self.agents = root / "agents"
        self.specs = root / "deploy" / "specs"
        self.releases = root / "deploy" / "releases"
        self.promote_command = promote_command
        self.header = f"# Generated by `{config_command}`. Do not edit.\n"

    # ------------------------------------------------------------ files

    def policy(self) -> Policy:
        path = self.root / "deploy" / "promotion.yaml"
        return Policy.of(yaml.safe_load(path.read_text()) if path.exists() else None)

    def load(self, env: str) -> dict[str, Any]:
        path = self.releases / f"{env}.yaml"
        return dict(yaml.safe_load(path.read_text()) or {}) if path.exists() else {}

    def save(self, env: str, data: dict[str, Any]) -> None:
        self.releases.mkdir(parents=True, exist_ok=True)
        head = (
            f"# What serves in {env} (Step 38). Changed only by `{self.promote_command}` in a"
            " pull request.\n"
        )
        (self.releases / f"{env}.yaml").write_text(head + yaml.safe_dump(data, sort_keys=True))

    def dev_version(self, agent: str) -> str:
        path = self.agents / agent / "agent.yaml"
        if not path.is_file():
            raise PromotionError(f"no agent {agent!r} in {self.agents}")
        return str(yaml.safe_load(path.read_text())["version"])

    def snapshot(self, agent: str, version: str) -> bool:
        """Copy agents/AGENT into deploy/specs/AGENT/VERSION; False if it is already there."""
        target = self.specs / agent / version
        if target.exists():
            return False
        source = self.agents / agent
        target.mkdir(parents=True)
        shutil.copy2(source / "agent.yaml", target / "agent.yaml")
        if (source / "workers").is_dir():
            shutil.copytree(source / "workers", target / "workers")
        return True

    # ------------------------------------------------------------ promotion

    def promote(
        self,
        agent: str,
        to: str | None = None,
        *,
        shadow: bool = False,
        full: bool = False,
        abort: bool = False,
        verdict: Mapping[str, Any] | None = None,
    ) -> Step:
        """Make one promotion step in the working tree. ``full`` needs the live ``verdict`` (the
        agent's entry in ``GET /v1/admin/releases``)."""
        policy = self.policy()
        if abort:
            prod = self.load("prod")
            entry = (prod.get("agents") or {}).get(agent) or {}
            if not entry.pop("candidate", None):
                raise PromotionError(f"prod has no candidate for {agent}")
            self.save("prod", prod)
            return Step("prod", str(entry["stable"]), "abort the candidate")
        if to == "staging":
            version = self.dev_version(agent)
            made = self.snapshot(agent, version)
            staging = self.load("staging")
            staging.setdefault("agents", {})[agent] = {"stable": version}
            self.save("staging", staging)
            return Step(
                "staging", version, f"serve {version}" + (" (new snapshot)" if made else "")
            )
        if to != "prod":
            raise PromotionError("give --to staging|prod or --abort")
        staging_version = ((self.load("staging").get("agents") or {}).get(agent) or {}).get(
            "stable"
        )
        if not staging_version:
            raise PromotionError(f"staging does not serve {agent}; promote it there first")
        prod = self.load("prod")
        agents = prod.setdefault("agents", {})
        entry = agents.get(agent)
        if full:
            cand = (entry or {}).get("candidate")
            if not cand:
                raise PromotionError(f"prod has no candidate for {agent}")
            if verdict is None:
                raise PromotionError("--full needs --api (or --verdict-file) for the online eval")
            online = verdict.get("online_eval") or {}
            if (verdict.get("candidate") or {}).get("rolled_back"):
                raise PromotionError(f"{cand['version']} was rolled back; it cannot go to prod")
            if online.get("decision") != "pass":
                raise PromotionError(
                    f"online evaluation of {cand['version']} is"
                    f" {online.get('decision')!r}, not 'pass': {online}"
                )
            version = str(cand["version"])
            agents[agent] = {k: v for k, v in entry.items() if k != "candidate"} | {
                "stable": version
            }
            what = f"full rollout of {version} (online eval passed: {online})"
        elif entry is None:
            version = staging_version
            agents[agent] = {"stable": version}
            what = f"first release of {version}"
        else:
            version = staging_version
            mode = "shadow" if shadow else "canary"
            entry["candidate"] = {"version": version, "mode": mode, "weight": policy.canary_weight}
            what = f"{version} as a {policy.canary_weight}% {mode} candidate"
        self.save("prod", prod)
        return Step("prod", str(version), what)

    @staticmethod
    def online_verdict(
        agent: str, api: str | None = None, verdict_file: str | None = None
    ) -> dict[str, Any]:
        """The agent's entry in the run API's release report (token in AGENT_API_TOKEN)."""
        if verdict_file:
            report = json.loads(Path(verdict_file).read_text())
        else:
            if not api:
                raise PromotionError("--full needs --api (or --verdict-file) for the online eval")
            req = urllib.request.Request(  # noqa: S310 - the operator's own API URL
                f"{api.rstrip('/')}/v1/admin/releases",
                headers={"Authorization": f"Bearer {os.environ.get('AGENT_API_TOKEN', '')}"},
            )
            with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310
                report = json.load(resp)
        entry = next((r for r in report["releases"] if r["agent"] == agent), None)
        if entry is None:
            raise PromotionError(f"the API does not serve {agent}")
        return dict(entry)

    def check(self, base: str | None = "HEAD", head: str | None = None) -> list[str]:
        """What breaks the promotion rules from ``base`` to ``head`` (None: the working tree)."""
        return problems(self.state_at(base), self.state_at(head), self.policy())

    def check_each(self, base: str, head: str = "HEAD") -> list[str]:
        """The promotion rules for every commit from ``base`` to ``head``, each against its
        parent. The rules are about single steps (a snapshot from dev, staging before a canary),
        so a push or pull request of many commits is judged step by step, not as one jump."""
        commits = self._git(
            "rev-list",
            "--reverse",
            "--first-parent",
            f"{base}..{head}",
            "--",
            "agents",
            "deploy/specs",
            "deploy/releases",
            "deploy/promotion.yaml",
        ).split()
        policy = self.policy()
        found: list[str] = []
        for commit in commits:
            before, after = self.state_at(f"{commit}^"), self.state_at(commit)
            found += [f"{commit[:7]}: {p}" for p in problems(before, after, policy)]
        return found

    def commit(self, agent: str, step: Step) -> str:
        """Put the step on a branch ``promote/<agent>-<version>-<env>`` for a pull request."""
        branch = f"promote/{agent}-{step.version}-{step.env}"
        git = ["git", "-C", str(self.root)]
        subprocess.run([*git, "switch", "-c", branch], check=True)  # noqa: S603
        subprocess.run([*git, "add", "deploy"], check=True)  # noqa: S603
        subprocess.run([*git, "commit", "-m", step.message(agent)], check=True)  # noqa: S603
        return branch

    # ------------------------------------------------------------ state at a commit

    def _git(self, *args: str) -> str:
        return subprocess.run(  # noqa: S603
            ["git", "-C", str(self.root), *args],  # noqa: S607
            check=True,
            capture_output=True,
            text=True,
        ).stdout

    def _read(self, ref: str | None, path: str) -> bytes | None:
        if ref is None:
            file = self.root / path
            return file.read_bytes() if file.is_file() else None
        try:
            return subprocess.run(  # noqa: S603
                ["git", "-C", str(self.root), "show", f"{ref}:{path}"],  # noqa: S607
                check=True,
                capture_output=True,
            ).stdout
        except subprocess.CalledProcessError:
            return None

    def _files(self, ref: str | None, prefix: str) -> list[str]:
        if ref is None:
            base = self.root / prefix
            if not base.exists():
                return []
            return sorted(str(p.relative_to(self.root)) for p in base.rglob("*.yaml"))
        out = self._git("ls-tree", "-r", "--name-only", ref, "--", prefix)
        return sorted(p for p in out.split() if p.endswith(".yaml"))

    def _version_files(self, ref: str | None, files: list[str], root: str) -> dict[str, bytes]:
        """agent.yaml and workers/*.yaml under ``root``, keyed relative to it."""
        out = {}
        for path in files:
            rel = path.removeprefix(root + "/")
            if rel == "agent.yaml" or (rel.startswith("workers/") and rel.count("/") == 1):
                data = self._read(ref, path)
                if data is not None:
                    out[rel] = data
        return out

    def state_at(self, ref: str | None) -> State:
        """The deployment state at a commit (None: the working tree)."""
        state = State()
        for env in ENVS:
            data = self._read(ref, f"deploy/releases/{env}.yaml")
            state.releases[env] = (
                dict((yaml.safe_load(data) or {}).get("agents") or {}) if data else {}
            )
        snaps = self._files(ref, "deploy/specs")
        for agent, version in sorted(
            {tuple(p.split("/")[2:4]) for p in snaps if p.count("/") >= 4}
        ):
            root = f"deploy/specs/{agent}/{version}"
            state.snapshots[(agent, version)] = tree_hash(
                self._version_files(ref, [p for p in snaps if p.startswith(root + "/")], root)
            )
        dev = self._files(ref, "agents")
        for agent in sorted({p.split("/")[1] for p in dev if p.count("/") >= 2}):
            root = f"agents/{agent}"
            files = self._version_files(ref, [p for p in dev if p.startswith(root + "/")], root)
            if "agent.yaml" in files:
                spec = yaml.safe_load(files["agent.yaml"]) or {}
                state.dev[agent] = (str(spec.get("version")), tree_hash(files))
        return state

    # ------------------------------------------------------------ generated deployment config

    def _dump(self, doc: Any) -> str:
        return self.header + yaml.safe_dump(doc, sort_keys=False)

    def head_specs(self) -> dict[Path, str]:
        """dev (``deploy/components/head-specs``): every spec in ``agents/``, mounted at
        ``/app/agents`` in the pods that run agents."""
        out = self.root / "deploy" / "components" / "head-specs"
        agents = (
            sorted(a for a in self.agents.iterdir() if a.is_dir()) if self.agents.exists() else []
        )
        paths = [f"{a.name}/{f}" for a in agents for f in version_files(a)]
        kustomization = {
            "apiVersion": "kustomize.config.k8s.io/v1alpha1",
            "kind": "Component",
            "configMapGenerator": [
                {"name": "agent-specs", "files": [f"{key(p)}=../../../agents/{p}" for p in paths]}
            ],
            "patches": [
                {
                    "path": "volume.yaml",
                    "target": {
                        "kind": "Deployment",
                        "labelSelector": "agent-platform/specs=mounted",
                    },
                }
            ],
        }
        volume = mount("agent-specs", "agent-specs", [(key(p), p) for p in paths], "/app/agents")
        return {
            out / "kustomization.yaml": self._dump(kustomization),
            out / "volume.yaml": self._dump(volume),
        }

    def released(self, env: str) -> dict[Path, str]:
        """staging, prod (``deploy/overlays/<env>/released``): the snapshots the environment's
        releases file names. agent-api mounts every named version at
        ``/app/versions/<agent>/<version>/`` with the releases file, so it can serve a canary or
        shadow candidate next to the stable version; agent-worker and a2a-gateway mount each
        agent's stable version at ``/app/agents/<agent>/``."""
        out = self.root / "deploy" / "overlays" / env / "released"
        entries = self.load(env).get("agents") or {}
        files: list[str] = []  # <agent>/<version>/<file>
        stable: list[tuple[str, str]] = []  # (key, <agent>/<file>)
        for agent, entry in sorted(entries.items()):
            versions = [str(entry["stable"])]
            if entry.get("candidate"):
                versions.append(str(entry["candidate"]["version"]))
            for version in versions:
                for f in version_files(self.specs / agent / version):
                    files.append(f"{agent}/{version}/{f}")
                    if version == str(entry["stable"]):
                        stable.append((key(f"{agent}/{version}/{f}"), f"{agent}/{f}"))
        kustomization = {
            "apiVersion": "kustomize.config.k8s.io/v1alpha1",
            "kind": "Component",
            "configMapGenerator": [
                {"name": "agent-specs", "files": [f"{key(p)}=../../../specs/{p}" for p in files]},
                {
                    "name": "agent-releases",
                    "files": [f"releases.yaml=../../../releases/{env}.yaml"],
                },
            ],
            "patches": [
                {"path": "agent-api.yaml", "target": {"kind": "Deployment", "name": "agent-api"}},
                {
                    "path": "stable.yaml",
                    "target": {"kind": "Deployment", "name": "agent-worker|a2a-gateway"},
                },
            ],
        }
        api = [
            *mount("agent-specs", "agent-specs", [(key(p), p) for p in files], "/app/versions"),
            *mount(
                "agent-releases",
                "agent-releases",
                [("releases.yaml", "releases.yaml")],
                "/app/releases",
            ),
            {
                "op": "add",
                "path": "/spec/template/spec/containers/0/env/-",
                "value": {"name": "AGENT_API_RELEASES", "value": "/app/releases/releases.yaml"},
            },
            {
                "op": "add",
                "path": "/spec/template/spec/containers/0/env/-",
                "value": {"name": "AGENT_API_VERSIONS_DIR", "value": "/app/versions"},
            },
        ]
        return {
            out / "kustomization.yaml": self._dump(kustomization),
            out / "agent-api.yaml": self._dump(api),
            out / "stable.yaml": self._dump(
                mount("agent-specs", "agent-specs", stable, "/app/agents")
            ),
        }

    def rendered(self) -> dict[Path, str]:
        files = self.head_specs()
        for env in ENVS:
            files |= self.released(env)
        return files

    def write_config(self) -> list[Path]:
        written = []
        for path, text in self.rendered().items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            written.append(path)
        return written

    def stale_config(self) -> tuple[int, list[Path]]:
        files = self.rendered()
        return len(files), [p for p, t in files.items() if not p.exists() or p.read_text() != t]
