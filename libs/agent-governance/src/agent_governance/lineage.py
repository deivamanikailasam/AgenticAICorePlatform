"""Lineage (Step 32): for each reference app, which spec version uses which prompts, models, tools
and datasets, down through its workers. The same identifiers appear in every audit event's
``versions`` (Step 31), so an event can be traced back to this graph and vice versa."""

from __future__ import annotations

import hashlib
from typing import Any

from agent_governance.cards import models
from agent_governance.inventory import Entry, Inventory


def _short(digest: str) -> str:
    return digest[:12]


def prompts(entry: Entry) -> list[dict[str, str]]:
    """Prompt registry refs by node, or the inline template's digest when there is no ref."""
    graph = entry.spec.graph
    out = []
    for n in graph.nodes if graph is not None else ():
        if n.prompt:
            out.append({"node": n.id, "prompt": n.prompt})
        elif isinstance(n.config.get("template"), str):
            digest = hashlib.sha256(n.config["template"].encode()).hexdigest()
            out.append({"node": n.id, "prompt": f"inline template sha256:{_short(digest)}"})
    return out


def datasets(entry: Entry, inv: Inventory) -> list[dict[str, Any]]:
    out = []
    if entry.spec.evals:
        suite = entry.spec.evals.suite
        out.append({"kind": "eval suite", "ref": suite, "in_repo": (inv.root / suite).exists()})
    lt = entry.spec.memory.long_term
    if lt is not None:
        out.append(
            {"kind": "long-term memory", "ref": f"{lt.store} ({lt.scope})", "in_repo": False}
        )
    for t in entry.spec.tools:
        if t.ref.startswith("mcp://rag-core/"):
            out.append({"kind": "retrieval corpus", "ref": "Project 0 rag-core", "in_repo": False})
    return out


def agent_lineage(entry: Entry, inv: Inventory) -> dict[str, Any]:
    tools = []
    for t in entry.spec.tools:
        card = inv.tool_cards.get(t.ref)
        tools.append({"ref": t.ref, "version": card["version"] if card else "per server"})
    return {
        "agent": entry.spec.name,
        "spec": {"path": str(entry.path), "version": entry.spec.version, "hash": entry.digest},
        "prompts": prompts(entry),
        "models": models(entry.spec, inv),
        "tools": tools,
        "datasets": datasets(entry, inv),
        "workers": [a.name for a in entry.spec.agents],
    }


def lineage(inv: Inventory) -> dict[str, Any]:
    return {
        "systems": [
            {
                "system": s.system,
                "agents": [agent_lineage(e, inv) for e in [s, *inv.workers_of(s.system)]],
            }
            for s in inv.systems()
        ]
    }


def _id(*parts: str) -> str:
    return "n" + hashlib.sha256("|".join(parts).encode()).hexdigest()[:10]


def _where(d: dict[str, Any]) -> str:
    if d["kind"] == "eval suite":
        return "" if d["in_repo"] else " (not in the repository yet)"
    return " (runtime data)"


def render(data: dict[str, Any]) -> str:
    out = [
        "# Lineage",
        "",
        "Generated by `just cards` from the specs and registries — do not edit by hand.",
        "",
        "For each reference app: spec → prompts → models → tools → datasets, through its workers. "
        "Spec hashes are the `spec_hash` in every audit event's `versions` (Step 31).",
        "",
    ]
    for system in data["systems"]:
        out += [f"## {system['system']}", "", "```mermaid", "flowchart LR"]
        nodes: list[str] = []
        edges: list[str] = []
        names = {a["agent"]: _id("spec", a["agent"]) for a in system["agents"]}
        for a in system["agents"]:
            sid = names[a["agent"]]
            nodes.append(
                f'  {sid}["{a["agent"]} {a["spec"]["version"]}<br/>{_short(a["spec"]["hash"])}"]'
            )
            for p in a["prompts"]:
                pid = _id("prompt", a["agent"], p["node"])
                nodes.append(f'  {pid}(["{p["node"]}: {p["prompt"]}"])')
                edges.append(f"  {sid} --> {pid}")
            for role, alias in a["models"].items():
                mid = _id("model", alias)
                nodes.append(f'  {mid}{{{{"{alias}"}}}}')
                edges.append(f"  {sid} -- {role} --> {mid}")
            for t in a["tools"]:
                tid = _id("tool", t["ref"])
                nodes.append(f'  {tid}[/"{t["ref"]} {t["version"]}"/]')
                edges.append(f"  {sid} --> {tid}")
            for d in a["datasets"]:
                did = _id("data", d["ref"])
                nodes.append(f'  {did}[("{d["kind"]}: {d["ref"]}")]')
                edges.append(f"  {sid} --> {did}")
            for w in a["workers"]:
                if w in names:
                    edges.append(f"  {sid} -- delegates --> {names[w]}")
                else:  # a worker named by its short name in the team spec
                    match = next((n for n in names if n.endswith(f"-{w}")), None)
                    if match:
                        edges.append(f"  {sid} -- delegates --> {names[match]}")
        out += list(dict.fromkeys(nodes)) + list(dict.fromkeys(edges))
        out += ["```", ""]
        out += [
            "| Agent | Spec | Prompts | Models | Tools | Datasets |",
            "|---|---|---|---|---|---|",
        ]
        for a in system["agents"]:
            out.append(
                f"| {a['agent']} | `{a['spec']['path']}` {a['spec']['version']} "
                f"`{_short(a['spec']['hash'])}` | "
                + ("<br/>".join(f"{p['node']}: {p['prompt']}" for p in a["prompts"]) or "-")
                + " | "
                + ", ".join(sorted(set(a["models"].values())))
                + " | "
                + ("<br/>".join(f"`{t['ref']}` {t['version']}" for t in a["tools"]) or "-")
                + " | "
                + (
                    "<br/>".join(f"{d['kind']}: {d['ref']}" + _where(d) for d in a["datasets"])
                    or "-"
                )
                + " |"
            )
        out.append("")
    return "\n".join(out)
