"""The AI-use register (Step 32): one entry per agent, in the shape AI-governance frameworks ask for
(purpose, owner, risk, autonomy, oversight, data, status), generated from the specs so it can't
fall behind them. Lifecycle status (draft, approved, ...) lives in the agent registry (Step 25) and
changes without a commit, so the register points to it rather than copying it."""

from __future__ import annotations

from typing import Any

from agent_governance.cards import agent_card
from agent_governance.inventory import Inventory


def register(inv: Inventory) -> dict[str, Any]:
    entries = []
    for e in inv.entries:
        card = agent_card(e, inv)
        entries.append(
            {
                "id": f"AI-{e.spec.name}",
                "agent": e.spec.name,
                "version": e.spec.version,
                "system": e.system,
                "purpose": card["purpose"],
                "owner": card["owner"],
                "risk_tier": card["risk_tier"],
                "autonomy": card["autonomy"],
                "models": sorted(set(card["models"].values())),
                "human_oversight": card["human_oversight"],
                "data": card["data"],
                "affected": "Users of the tenant that runs it, and the people or records its tools act on",
                "status": "see `just agents` (agent registry lifecycle)",
                "card": f"docs/cards/agents/{e.spec.name}.md",
            }
        )
    return {"entries": entries}


def render(data: dict[str, Any]) -> str:
    out = [
        "# AI-use register",
        "",
        "Generated by `just cards` from the specs — do not edit by hand. One entry per agent; "
        "lifecycle status is in the agent registry (`just agents`).",
        "",
        "| ID | Agent | System | Purpose | Owner | Risk | Autonomy | Human oversight | Card |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in data["entries"]:
        oversight = "<br/>".join(r["human_oversight"])
        out.append(
            f"| {r['id']} | {r['agent']} {r['version']} | {r['system']} | {r['purpose']} "
            f"| {r['owner']} | {r['risk_tier']} | {r['autonomy']} | {oversight} "
            f"| [card](../cards/agents/{r['agent']}.md) |"
        )
    out.append("")
    return "\n".join(out)
